package org.gonza.kotlinplayground

import org.gonza.kotlinplayground.domain.lotto.BonusNumber
import org.gonza.kotlinplayground.domain.lotto.LottoNumber
import org.gonza.kotlinplayground.domain.lotto.LottoTicket
import org.gonza.kotlinplayground.domain.payment.BonusLottoStatisticsSheet
import org.gonza.kotlinplayground.domain.payment.GeneralLottoStatisticsSheet
import org.gonza.kotlinplayground.domain.payment.Payment
import org.gonza.kotlinplayground.domain.payment.WinningStatisticsResult
import org.gonza.kotlinplayground.presentation.InputView
import org.gonza.kotlinplayground.presentation.OutputView
import org.gonza.kotlinplayground.service.*

fun main() {
    val inputView = InputView()
    val outputView = OutputView()

    val payment = purchaseLotto(inputView, outputView)
    val totalPaidTicketCount = LottoTicket.getPaidTicketCount(payment)
    val manualTicketCount =
        purchaseManualTicketCount(
            inputView = inputView,
            outputView = outputView,
            paidTicketCount = totalPaidTicketCount,
        )
    val manualLottoTicketList =
        purchaseManualLottoTicketList(
            inputView = inputView,
            outputView = outputView,
            paidManualTicketCount = manualTicketCount,
        )
    val autoGenerateTicketCount = totalPaidTicketCount - manualTicketCount
    val autoGeneratedLottoTicketList = generateLottoTickets(autoGenerateTicketCount)
    val totalLottoTicketList = autoGeneratedLottoTicketList + manualLottoTicketList

    outputView.printPurchasedLottoTicketCount(manualTicketCount, autoGenerateTicketCount)
    outputView.printGeneratedLottoTicketList(totalLottoTicketList)

    val winningTicket = getWinningTicket(inputView, outputView)
    val bonusNumber = getBonusNumber(winningTicket, inputView, outputView)
    val winningStatistics = matchLottoResults(winningTicket, totalLottoTicketList)
    val bonusStatistics = matchBonusLottoResults(winningTicket, bonusNumber, totalLottoTicketList)
    val allStatistics = winningStatistics.add(bonusStatistics)

    printStatistics(outputView, allStatistics)
    printReturnOnInvestment(outputView, payment, allStatistics)
}

private fun purchaseLotto(
    inputView: InputView,
    outputView: OutputView,
): Payment {
    outputView.printRequestPurchasePrice()
    val purchaseAmount =
        inputView.read()?.toIntOrNull()
            ?: throw IllegalArgumentException("올바른 금액을 입력하세요")
    return Payment(purchaseAmount)
}

private fun purchaseManualTicketCount(
    inputView: InputView,
    outputView: OutputView,
    paidTicketCount: Int,
): Int {
    outputView.printManualPurchaseLottoCount()
    val paidManualTicketCount =
        inputView.read()?.toIntOrNull()
            ?: throw IllegalArgumentException("올바른 숫자를 입력해주세요")

    if (paidTicketCount < paidManualTicketCount) {
        throw IllegalArgumentException("구매한 티켓 개수를 초과했습니다.")
    }

    return paidManualTicketCount
}

private fun purchaseManualLottoTicketList(
    inputView: InputView,
    outputView: OutputView,
    paidManualTicketCount: Int,
): List<LottoTicket> {
    outputView.printRequestManualPurchaseLottoTicket()
    val result = inputView.readMultipleByCount(paidManualTicketCount)

    return result.map {
        if (it == null) {
            throw IllegalArgumentException("올바른 번호를 입력해주세요.")
        }

        InputLottoPicker(it).pick()
    }
}

private fun generateLottoTickets(paidTicketCount: Int): List<LottoTicket> {
    val randomNumberGenerator = RandomNumberGenerator(LottoNumber.Range())
    val lottoGenerator = LottoGenerator(randomNumberGenerator)
    return List(paidTicketCount) {
        lottoGenerator.generate().ticket
    }
}

private fun getWinningTicket(
    inputView: InputView,
    outputView: OutputView,
): LottoTicket {
    outputView.printRequestResultLottoTicket()
    val winningLottoInput =
        inputView.read()
            ?: throw IllegalArgumentException("당첨 번호를 입력하세요")
    return InputLottoPicker(winningLottoInput).pick()
}

private fun getBonusNumber(
    winningTicket: LottoTicket,
    inputView: InputView,
    outputView: OutputView,
): BonusNumber {
    outputView.printBonusNumber()
    val bonusNumber =
        inputView.read()?.toIntOrNull()
            ?: throw IllegalArgumentException("보너스 숫자를 입력하세요")
    return BonusNumber(winningTicket, bonusNumber)
}

private fun matchLottoResults(
    winningTicket: LottoTicket,
    purchasedTicketList: List<LottoTicket>,
): WinningStatisticsResult {
    val lottoMatcher = GeneralLottoMatcher(winningTicket)
    return lottoMatcher.getWinningStatistics(
        purchasedTicketList = purchasedTicketList,
    )
}

private fun matchBonusLottoResults(
    winningTicket: LottoTicket,
    bonusNumber: BonusNumber,
    purchasedTicketList: List<LottoTicket>,
): WinningStatisticsResult {
    val bonusLottoMatcher = BonusNumberMatcher(winningTicket, bonusNumber)
    return bonusLottoMatcher.getWinningStatistics(
        purchasedTicketList = purchasedTicketList,
    )
}

private fun printStatistics(
    outputView: OutputView,
    winningStatisticsResult: WinningStatisticsResult,
) {
    outputView.printNoticeStatisticSheet()
    val totalStatistics = GeneralLottoStatisticsSheet.entries + BonusLottoStatisticsSheet.entries

    totalStatistics.forEach {
        val winningInfo = winningStatisticsResult.findWinningInfoBy(it)
        val matchedCount = winningInfo?.count ?: 0

        outputView.printStatisticSheet(it, matchedCount)
    }
}

private fun printReturnOnInvestment(
    outputView: OutputView,
    payment: Payment,
    winningStatisticsResult: WinningStatisticsResult,
) {
    val profitPayment = winningStatisticsResult.totalPrizePayment() ?: return outputView.printReturnOnInvestment(0.00)

    val financialPolicy = LottoFinancialPolicy()
    val returnOnInvestment = financialPolicy.calculateReturnOnInvestment(payment, profitPayment)

    outputView.printReturnOnInvestment(returnOnInvestment)
}
